// Dynamicky skladane texty (findings.js) — preklad cez vzor.
const PATTERNS_SK = [
  [/^(\d+) known CVEs? for this service version \(max CVSS ([\d.]+)\)$/, (m) => `${m[1]} ${Number(m[1]) === 1 ? 'známa CVE' : Number(m[1]) < 5 ? 'známe CVE' : 'známych CVE'} pre túto verziu služby (max. CVSS ${m[2]})`],
  [/^(.+): vulnerable$/, (m) => `${m[1]}: zraniteľné`],
];

/** Preklad textu z databazy oprav; neznamy text (napr. z vystupu nmapu) ostava bez zmeny. */
export function tr(text, lang) {
  if (lang !== 'sk' || typeof text !== 'string') return text;
  if (Object.prototype.hasOwnProperty.call(SK, text)) return SK[text];
  for (const [re, fn] of PATTERNS_SK) {
    const m = text.match(re);
    if (m) return fn(m);
  }
  return text;
}

export function labels(lang) {
  return LABELS[lang] || LABELS.en;
}
